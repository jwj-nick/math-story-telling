NEW = []
for u in range(1, 12):
    d = json.load(io.open(ROOT + 'math2/u%02d/practice.json' % u, encoding='utf-8'))
    cat = json.load(io.open(ROOT + 'misconceptions/math2_u%02d.json' % u, encoding='utf-8'))['items']
    for t in d['types']:
        ok(len(t['problems']) == 4, 'u%02d 유형%d 4문항' % (u, t['no']), len(t['problems']))
        lv = [p['level'] for p in t['problems']]
        ok('L' in lv and 'M' in lv, 'u%02d 유형%d 에 L·M 둘 다' % (u, t['no']), ''.join(lv))
        ids = [p['id'] for p in t['problems']]
        ok(len(set(ids)) == 4, 'u%02d 유형%d id 중복 없음' % (u, t['no']), ids)
        for p in t['problems']:
            if p.get('origin') != 'authored':
                continue
            NEW.append((u, t['no'], p))
            tag = '%s' % p['id']
            ok(bool(p['stem_print']) and len(p['stem_print']) > 15, tag + ' 발문')
            ok(bool(p['hint']) and len(p['hint']) > 10, tag + ' 힌트')
            ok(bool(p['solution']) and len(p['solution']) > 30, tag + ' 해설')
            ok(bool(p['answer_atoms']) and bool(p['answer_print']), tag + ' 정답')
            ok(bool(p['answer_format']), tag + ' 답 형식 안내')
            ok('<sup>' not in (p['answer_unit'] or ''), tag + ' 단위는 유니코드', p['answer_unit'])
            ok(len(p['misconceptions']) >= 2, tag + ' 오개념 2개 이상', p['misconceptions'])
            for c in p['misconceptions']:
                ok(c in cat, tag + ' 오개념 코드 실재', c)
            ok('□' not in p['stem_print'] and '슬라이더' not in p['stem_print'],
               tag + ' 앱 의존 표현 없음')
            ok(p['work_space'] in ('sm', 'md', 'lg'), tag + ' 풀이 공간', p['work_space'])
            # 해설이 발문을 그대로 베끼지 않았는지
            ok(p['solution'] != p['stem_print'], tag + ' 해설이 발문과 다름')

ok(len(NEW) == 87, '이번에 유형당 4문항으로 채운 새 문항 87개', len(NEW))

# ── 2) 수학 독립 검산 ────────────────────────────────────────
A = {p['id']: (p['answer_atoms'], re.sub(r'<[^>]+>', '', p['answer_print'])) for _, _, p in NEW}


